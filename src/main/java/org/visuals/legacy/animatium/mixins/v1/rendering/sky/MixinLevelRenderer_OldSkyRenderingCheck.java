package org.visuals.legacy.animatium.mixins.v1.rendering.sky;

import com.llamalad7.mixinextras.expression.Definition;
import com.llamalad7.mixinextras.expression.Expression;
import com.llamalad7.mixinextras.sugar.Local;
import net.minecraft.client.Minecraft;
import net.minecraft.client.renderer.GameRenderer;
import org.spongepowered.asm.mixin.Final;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.Shadow;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.ModifyArg;
import org.visuals.legacy.animatium.config.AnimatiumConfig;

@Mixin(GameRenderer.class)
public abstract class MixinLevelRenderer_OldSkyRenderingCheck {
    @Shadow
    @Final
    private Minecraft minecraft;

    @Definition(id = "renderSky", local = @Local(type = boolean.class, ordinal = 1, argsOnly = true))
    @Expression("renderSky")
    @ModifyArg(method = "renderLevel", at = @At(value = "INVOKE", target = "Lnet/minecraft/client/renderer/LevelRenderer;renderLevel(Lcom/mojang/blaze3d/resource/GraphicsResourceAllocator;Lnet/minecraft/client/DeltaTracker;ZLnet/minecraft/client/renderer/state/level/CameraRenderState;Lorg/joml/Matrix4fc;Lcom/mojang/blaze3d/buffers/GpuBufferSlice;Lorg/joml/Vector4f;ZLnet/minecraft/client/renderer/chunk/ChunkSectionsToRender;)V"), index = 9)
    private boolean animatium$oldSkyRenderingCheck(boolean original) {
        if (AnimatiumConfig.instance().fixes.oldSkyRenderingCheck) {
            original = original && this.minecraft.options.getEffectiveRenderDistance() >= 4;
        }

        return original;
    }
}
